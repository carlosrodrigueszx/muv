CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    telefone VARCHAR(20) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL
);

CREATE TABLE passageiros (
    usuario_id BIGINT PRIMARY KEY
        REFERENCES usuarios(id)
);

CREATE TABLE motoristas (
    usuario_id BIGINT PRIMARY KEY
        REFERENCES usuarios(id),
    cnh VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE veiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(50) NOT NULL,
    modelo VARCHAR(100) NOT NULL,
    ano INTEGER NOT NULL,
    cor VARCHAR(50) NOT NULL,
    placa VARCHAR(10) NOT NULL UNIQUE,
    capacidade_assentos INTEGER NOT NULL
        CHECK (capacidade_assentos > 0)
);

CREATE TABLE rotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem VARCHAR(150) NOT NULL,
    destino VARCHAR(150) NOT NULL
);

CREATE TABLE viagens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rota_id BIGINT NOT NULL REFERENCES rotas(id),
    motorista_id BIGINT NOT NULL
        REFERENCES motoristas(usuario_id),
    veiculo_id BIGINT NOT NULL REFERENCES veiculos(id),
    partida_prevista TIMESTAMPTZ NOT NULL,
    chegada_prevista TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PROGRAMADA',
    CHECK (chegada_prevista > partida_prevista)
);

CREATE INDEX idx_viagens_rota_partida
    ON viagens(rota_id, partida_prevista);
